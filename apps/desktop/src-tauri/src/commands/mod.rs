use std::sync::Arc;

use nc_launcher::LauncherError;
use nc_store::{Store, StoreError};
use serde::Serialize;

use crate::state::AppState;

#[derive(Debug, Serialize)]
pub struct CmdError {
    pub code: &'static str,
    pub message: String,
}

impl CmdError {
    pub fn new(code: &'static str, message: impl Into<String>) -> Self {
        Self {
            code,
            message: message.into(),
        }
    }
}

impl From<LauncherError> for CmdError {
    fn from(e: LauncherError) -> Self {
        Self::new(e.code(), e.to_string())
    }
}

impl From<nc_core::CoreError> for CmdError {
    fn from(e: nc_core::CoreError) -> Self {
        LauncherError::from(e).into()
    }
}

impl From<nc_launcher::auth::AuthError> for CmdError {
    fn from(e: nc_launcher::auth::AuthError) -> Self {
        LauncherError::from(e).into()
    }
}

impl From<StoreError> for CmdError {
    fn from(e: StoreError) -> Self {
        let code = match &e {
            StoreError::NotFound => "not_found",
            StoreError::Invalid(_) => "invalid_input",
            StoreError::NewerSchema { .. } => "db_newer",
            _ => "db",
        };
        Self::new(code, e.to_string())
    }
}

pub type Result<T> = std::result::Result<T, CmdError>;

pub fn invalid(message: impl Into<String>) -> CmdError {
    CmdError::new("invalid_input", message)
}

impl AppState {
    pub fn db(&self) -> Result<Arc<Store>> {
        self.store.clone().ok_or_else(|| {
            CmdError::new(
                "db_unavailable",
                self.startup_error
                    .clone()
                    .unwrap_or_else(|| "database unavailable".into()),
            )
        })
    }
}

/// Run a store call on the blocking pool.
pub async fn with_db<T: Send + 'static>(
    state: &AppState,
    f: impl FnOnce(&Store) -> std::result::Result<T, StoreError> + Send + 'static,
) -> Result<T> {
    let db = state.db()?;
    tauri::async_runtime::spawn_blocking(move || f(&db))
        .await
        .map_err(|e| CmdError::new("internal", e.to_string()))?
        .map_err(Into::into)
}

/// Version ids come from the WebView: accept only characters official ids use.
pub fn validate_version_id(id: &str) -> Result<()> {
    let ok = !id.is_empty()
        && id.len() <= 64
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_' | ' '))
        && nc_core::paths::validate_segment(id).is_ok();
    if ok {
        Ok(())
    } else {
        Err(invalid("invalid version id"))
    }
}

/// Instance ids are UUIDs generated by the store.
pub fn validate_instance_id(id: &str) -> Result<()> {
    let ok = id.len() == 36 && id.chars().all(|c| c.is_ascii_hexdigit() || c == '-');
    if ok {
        Ok(())
    } else {
        Err(invalid("invalid instance id"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn version_id_validation() {
        for ok in ["1.21.1", "26.3", "26.4-snapshot-7", "1.14 Pre-Release 1"] {
            assert!(validate_version_id(ok).is_ok(), "{ok}");
        }
        for bad in [
            "",
            "..",
            "../x",
            "a/b",
            "a\\b",
            "C:x",
            "x;calc",
            "con",
            &"x".repeat(65),
        ] {
            assert!(validate_version_id(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn instance_id_validation() {
        assert!(validate_instance_id("3f2b8c1e-0000-4000-8000-123456789abc").is_ok());
        for bad in [
            "",
            "x",
            "../../../../../../../../../../../../..",
            "3f2b8c1e-0000-4000-8000-123456789abz",
        ] {
            assert!(validate_instance_id(bad).is_err(), "{bad}");
        }
    }
}
